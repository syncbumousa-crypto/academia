-- ============================================================
--  م٢ — المساهمات المنشورة
-- ============================================================
--  ولا يُخزَّن إلّا **ما نُشر صراحةً** (‎p.st === 'pub'‎). وما كان «غير مدرج»
--  أو «خاصّ» يبقى في درج صاحبه ولا يبلغ الخادمَ أصلًا — لا يُرفع ثمّ يُحجب.
--
--  ===== و‎data‎ نصٌّ مبهم لا يفهمه الخادم =====
--  متنُ المساهمة يختلف اختلافًا تامًّا بين البنود التسعة: شجرةُ بطائقَ ذاتُ
--  عقدٍ متداخلة، أو قائمةُ مقاطع، أو جدولُ درجات، أو وصفُ مادّة. فلو حاول
--  الخادمُ أن يفهم كلَّ شكلٍ لَصار مخطّطُه صورةً ثانيةً من الموقع تتخلّف عنه
--  عند كلّ تعديل.
--  فيحفظه **كما هو**: يتحقّق من صاحبه وحجمه، لا من شكله. والموقعُ وحدَه يفهم.
--
--  ===== والمعرّف من العميل =====
--  صار فريدًا في الدنيا (‎state.idSeed‎)، وهو نفسُه في درج صاحبه — فيُمسك
--  الطرفان الخيطَ نفسَه، ولا يُحتاج إلى جدول ترجمةٍ بين معرّفَين.
-- ============================================================

CREATE TABLE IF NOT EXISTS posts (
  id      TEXT PRIMARY KEY,
  uid     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code    TEXT NOT NULL,              -- 'MIS 301' — وقد يكون مفتاحَ معملٍ كذلك
  sec     TEXT NOT NULL,              -- info · doc · grade · abs · srcU · srcP · lessons · videos · cards
  data    TEXT NOT NULL,              -- JSON خام
  ts      INTEGER NOT NULL,           -- متى كُتبت أوّلَ مرّة (من العميل: تاريخُ المساهمة)
  updated INTEGER NOT NULL            -- متى وصلت الخادمَ آخِرَ مرّة (من الخادم)
);

-- القراءةُ الغالبة: «مساهماتُ هذه المادّة» — فهرسٌ عليها
CREATE INDEX IF NOT EXISTS idx_posts_code ON posts(code, sec);
-- و«مساهماتي» في صفحة الحساب لاحقًا
CREATE INDEX IF NOT EXISTS idx_posts_uid  ON posts(uid);

-- ولمساهمةٍ واحدةٍ لكلّ صاحبٍ في كلّ بندٍ من كلّ مادّة: هو نموذج الموقع
-- (‎myPost‎ تجد الواحدةَ أو تُنشئها)، ويمنع الجدولُ ما يمنعه الموقع
CREATE UNIQUE INDEX IF NOT EXISTS idx_posts_one ON posts(uid, code, sec);
