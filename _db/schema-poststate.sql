--  حالُ النشر تُحفظ مع المساهمة
-- ============================================================
--  «المتصفّحُ لا يخزّن شيئًا» يقتضي أن تسكن **مسوّدتُك** حسابَك كذلك — وإلّا
--  ضاع ما لم تنشره بمجرّد تحديث الصفحة. وكان الدفعُ لا يرفع إلّا ‎st = 'pub'‎.
--
--  فتُرفع كلُّها وتُحفظ حالُها معها. والقراءةُ تفرّق:
--    · مساهماتي   ⇒ تُردّ كلُّها بحالها (مسوّدةً كانت أو منشورة)
--    · مساهماتُ غيري ⇒ لا يُردّ منها إلّا ‎pub‎ — ولا يُطّلع على مسوّدة أحد
--
--  والافتراضُ ‎pub‎: كلُّ ما رُفع قبل اليوم رُفع منشورًا (الدفعُ كان يشترطه).
ALTER TABLE posts ADD COLUMN st TEXT NOT NULL DEFAULT 'pub';
