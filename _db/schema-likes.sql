-- ============================================================
--  م٣أ — الإعجاب
-- ============================================================
--  ولا يُخزَّن **عدَّاد** بل تُخزَّن **الأفعال**: صفٌّ لكلّ (مساهمة، معجِب).
--  والعدُّ يُحسب بالاستعلام.
--
--  ولمَ لا عمودُ ‎likes‎ في ‎posts‎ يُزاد وينقص؟ لأنّ العدّادَ يكذب ولا يُصلَح:
--  طلبان في اللحظة نفسها يضيع أحدُهما، وشبكةٌ تنقطع في وسط الزيادة تتركه
--  زائدًا واحدًا إلى الأبد، ولا يُعرف بعدها مَن أعجب فلا يُطرح إعجابُه.
--  والصفوفُ لا تكذب: من أعجب فله صفّ، ومن رجع مُحي صفُّه، والعدُّ ما بقي.
--
--  والمفتاحُ المركّب يمنع الإعجابَ مرّتين — قيدٌ في القاعدة لا فحصٌ في الشيفرة،
--  فلا يُلتفّ عليه بطلبٍ مصنوع.
-- ============================================================

CREATE TABLE IF NOT EXISTS likes (
  pid  TEXT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  uid  TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ts   INTEGER NOT NULL,
  PRIMARY KEY (pid, uid)
);

-- «كم أُعجب بهذه؟» — والمفتاحُ المركّب يخدم البادئةَ ‎pid‎ فلا فهرسَ ثانٍ لها.
-- وهذا الفهرسُ للسؤال المقلوب: «بماذا أُعجبتُ أنا؟» (صفحةُ الحساب لاحقًا)
CREATE INDEX IF NOT EXISTS idx_likes_uid ON likes(uid);
