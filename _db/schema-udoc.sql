-- ============================================================
--  وثائقُ المستخدم — كلُّ ما يخصُّ صاحبَه في السحابة
-- ============================================================
--  حكمُ صاحب الموقع: المتصفّحُ لا يخزّن شيئًا إلّا أنّك مسجَّل. وما سواه في
--  الحساب. فبدل نقطةٍ لكلّ نوع (نواةٌ ثمّ اختباراتٌ ثمّ جدولةُ مذاكرةٍ…)
--  وثيقةٌ واحدةٌ بمفتاحين: صاحبُها ونوعُها.
--
--  ===== ولمَ وثائقُ لا جدولٌ لكلّ نوع؟ =====
--  الأنواعُ تنمو، وشكلُ كلٍّ منها يتبدّل في العميل. ولو فُسِّرت في القاعدة
--  لاحتاج كلُّ حقلٍ جديدٍ هجرةً. والخادمُ ههنا صندوقٌ أمينٌ يحفظ ولا يفسّر.
--
--  ===== وتُقرأ عند الحاجة لا كلُّها في الإقلاع =====
--  سجلُّ الاختبارات لا يُقرأ إلّا حين تُفتح صفحتُه. فالتقسيمُ بالنوع يجعل كلَّ
--  شاشةٍ تجلب ما يخصُّها وحدَه — ولا تُنقل مئاتُ الكيلوات في كلّ فتحة.
CREATE TABLE IF NOT EXISTS udoc (
  uid     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind    TEXT NOT NULL,               -- 'nook' · 'exams' · 'srs' · …
  data    TEXT NOT NULL,               -- JSON خام
  rev     INTEGER NOT NULL DEFAULT 1,
  updated INTEGER NOT NULL,
  PRIMARY KEY (uid, kind)
);
