-- ============================================================
--  م٤ — بِتاتُ الصور المنشورة
-- ============================================================
--  ===== المفتاحُ هو المحتوى =====
--  ‎k‎ تجزئةُ البِتات (SHA-256). فالصورةُ الواحدةُ تُخزَّن مرّةً مهما نشرها من
--  نشر، ورفعُها ثانيةً لا يزيد شيئًا. وثمرتُه الثانية أنّ العنوانَ **أبديّ**:
--  محتوًى واحدٌ لا يتغيّر تحت مفتاحٍ لا يتغيّر — فيُخبَّأ سنةً بلا خوف.
--
--  ===== ولمَ في D1 لا في R2؟ =====
--  R2 هو الموضع الصحيح (رخيصٌ، مصمَّمٌ للبِتات، بلا حدّ صفّ). ولم يكن مفعَّلًا
--  في الحساب يومَ بُني هذا، والعلّةُ التي يعالجها لا تنتظر: صورةُ ‎data-mid‎ لا
--  تسافر أصلًا فيراها القارئُ فراغًا.
--  فالبِتاتُ ههنا مؤقّتًا، والتصميمُ يجعل النقلَ تبديلَ دالّتين (‎mediaPut‎ و
--  ‎mediaGet‎): المفتاحُ نفسُه، والعنوانُ نفسُه، والعميلُ لا يعلم أين تسكن.
--
--  والحجمُ محدود: الصورةُ الواحدةُ لا تتجاوز ميجابايتًا. وأكبرُ صورةٍ في مجموعة
--  البطائق المنقولة ٣٥٤ كيلو، فالحدُّ واسعٌ ولا يضيق بالواقع.
-- ============================================================

CREATE TABLE IF NOT EXISTS media (
  k     TEXT PRIMARY KEY,          -- sha256(hex) للبِتات
  mime  TEXT NOT NULL,
  size  INTEGER NOT NULL,
  bytes BLOB NOT NULL,
  uid   TEXT NOT NULL,             -- أوّلُ من رفعها (لا مالكٌ حصريّ: المحتوى مشترك)
  ts    INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_media_uid ON media(uid);
