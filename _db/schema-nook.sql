-- ============================================================
--  نواةُ الركن — أترامُك ومكتبتُك وتواريخُك، في حسابك
-- ============================================================
--  المساهماتُ والبطائقُ صارت في الخادم، والنواةُ وحدَها بقيت في مفتاحٍ واحدٍ
--  في متصفّحٍ واحد. فضاعت أترامُ صاحب الموقع بموادها وتواريخها، ولا نسخةَ
--  لها في مكان. فتسكن حسابَه كما سكنته المساهمات.
--
--  ===== صفٌّ واحدٌ لكلّ حساب =====
--  ليست مساهماتٍ تُعدّ، بل حالُ صاحبها. فالمفتاحُ ‎uid‎، والمتنُ ‎JSON‎ خامٌ
--  يفهمه العميلُ وحدَه — كما في ‎posts.data‎ سواءً بسواء: الخادمُ يحفظ ولا
--  يفسّر، فيتبدّل شكلُ النواة في العميل بلا هجرةٍ ههنا.
--
--  ===== و‎rev‎ يزيد مع كلّ كتابة =====
--  به يعرف المتصفّحُ أنّ غيرَه كتب بعده. و‎updated‎ ساعةُ الخادم لا ساعةُ
--  الجهاز — فساعاتُ الأجهزة تكذب وتختلف، وحُكمُ «الأحدثُ يعلو» لا يُبنى عليها.
CREATE TABLE IF NOT EXISTS nook (
  uid     TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  data    TEXT NOT NULL,               -- JSON: {terms, libs, termDates, lastNook, termAt, termsGone}
  rev     INTEGER NOT NULL DEFAULT 1,
  updated INTEGER NOT NULL
);
