-- ---------- صاحبُ الموقع ومَن مُنع ----------
--  ‎admin‎ يُمنح بيدٍ لا يُطلب: لا نقطةَ تجعل أحدًا مشرفًا، ولا أوّلَ مسجِّلٍ
--  يرثها (سباقٌ يكسبه الغريب). يُكتب بأمرٍ على القاعدة، وهذا وحدَه بابُه.
--  و‎banned‎ يمنع الدخولَ والكتابةَ ولا يمحو ما كُتب: المحوُ فعلٌ منفصلٌ يُقصد.
ALTER TABLE users ADD COLUMN admin  INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN banned INTEGER NOT NULL DEFAULT 0;

-- ---------- عدّادُ الطلبات ----------
--  ولا يُخزَّن سجلُّ كلّ طلب: يُخزَّن **عدُّ نافذةٍ زمنيّة**. صفٌّ لكلّ
--  (فعل، صاحب، نافذة) — فالجدولُ لا ينمو بعدد الطلبات بل بعدد الفاعلين.
--  والصاحبُ عنوانُ الشبكة أو معرّفُ الحساب: يُحسب في الوسيط.
CREATE TABLE IF NOT EXISTS hits (
  k   TEXT NOT NULL,        -- 'join|1.2.3.4'
  win INTEGER NOT NULL,     -- رقمُ النافذة (الثواني ÷ طولها)
  n   INTEGER NOT NULL,
  PRIMARY KEY (k, win)
);
-- والكنسُ عند الكتابة: لا حارسَ دوريَّ في هذا المعمار
CREATE INDEX IF NOT EXISTS idx_hits_win ON hits(win);

-- ---------- حصّةُ الرفع ----------
--  تُحسب من ‎media‎ نفسِه (‎uid‎ و‎ts‎ فيه)، فلا جدولَ ثالث. وهذا الفهرسُ
--  يجعل السؤالَ «كم رفع فلانٌ اليوم؟» قراءةَ فهرسٍ لا مسحَ جدول.
CREATE INDEX IF NOT EXISTS idx_media_uid_ts ON media(uid, ts);
