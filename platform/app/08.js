  /* ===== إعدادُ ما يقع عند الحفظ — ترسٌ عائمٌ يسارَ المسار =====
     الآليّةُ آليّةُ «＋» في المحرّر: مِقبضٌ وحده مطويًّا، فإذا فُتح تمدّدت الحبّةُ يسارًا
     (نحو الفراغ لا نحو المسار) وظهر ما فيها. فلا يُرمى إعدادٌ في شريطٍ عمادُه الوجهةُ وزرُّها.
     والسطرُ واحدٌ مضغوط (اتّجاه «٥» في ‎card-chain-lab‎): «عند الحفظ:» ثمّ مفتاحان.
     والثاني تابعٌ للأوّل ويخفت إن أُطفئ — لا تُفتح أخرى والبطاقةُ باقيةٌ في يدك */
  /* ===== حالُ الترس تُقلب على العنصر القائم لا بإعادة بنائه =====
     كان الضغطُ يستدعي ‎renderCardDlg‎، وهي تكتب ‎innerHTML‎ للشريط كلِّه — فيُهدم الشريطُ
     ويُولد غيرُه وعليه صنفُ حاله. وعنصرٌ يُولد مفتوحًا **لا حالَ له سابقةً ينتقل منها**،
     فلا انتقالَ يقع مهما كُتب له في الملفّ: يظهر ظهورًا ويغيب غيابًا.
     فالانسيابُ لا يُنال بضبط المنحنيات بل بإبقاء العنصر حيًّا وقلبِ صنفه عليه */
