  const xtCur = () => (xtRun && xtRun.i < xtRun.q.length) ? xtRun.q[xtRun.i] : null;
  /* الكشف: Enter في طور السؤال. والمتعدد المخفي يكشف خياراته لا جوابه */
  /* ===== والكشفُ درجةٌ أو درجتان =====
     في الأنواع الثلاثة درجةٌ واحدة: ‎ask‎ ← ‎show‎. وفي المتعدّد إن خُبّئت خياراتُه
     بالإعداد فدرجتان: ‎ask‎ ← ‎pick‎ (تُبسط الخيارات) ← ‎show‎ (يُعلَن الصواب).
     ولا يُكشف على محكومٍ له: من اختار خيارًا فقد حُكم له في ‎xtPick‎، والكشفُ بعده عبث */
  function xtReveal() {
    const R = xtRun, u = xtCur();
    if (!R || !u || R.judged) return;
    if (R.phase === 'ask') {
      R.phase = (u.k === 'q' && xtS.kopt.q === 'without') ? 'pick' : 'show';
      /* وبسطُ الخيارات ليس ظهورًا للجواب: ‎pick‎ لمّا يُعلَن فيه الصوابُ بعد */
      if (R.phase === 'show') xtShown(u);
      xtPaint(); return;
    }
    if (u.k === 'q' && R.phase === 'pick') { R.phase = 'show'; xtShown(u); xtPaint(); }
  }
  /* ===== وخروجُ الجواب: يوقف الزمنَ، ويحكم على المتعدّد الذي لم يُختَر فيه =====
     ‏‎xtNoAns‎ تُصوّت بنفسها فلا يُنادى ‎xtSndA‎ معها — وإلّا اجتمع صوتان في لحظة */
  function xtShown(u) {
    const R = xtRun;
    if (u.k === 'q' && R.pick === null && !R.judged) { xtNoAns(u); return; }
    xtSpentStop(); xtSndA();
  }
