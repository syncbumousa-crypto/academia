  /* ============================================================
     وخيطُ الحافّة معه — «الحافّة» و«الورقة» معًا (‎xt-timer-lab#edge‎)
     ============================================================
     الورقةُ تقول الوقتَ **رقمًا** لمن نظر، والخيطُ يقوله **قدرًا** لمن لم ينظر: حدُّ
     الذيل العلويُّ نفسُه ينحسر ببطءٍ تراه بطرف عينك ولا تصرف إليه انتباهًا. فيجتمع
     التدقيقُ والإحساس، ولا يزاحم أحدُهما الآخرَ لأنّهما في حاسّتين.
     وهو ابنُ الذيل لا ابنُ الركن: يمتدّ على عرضه كلِّه فلا يسكن زاويةً.
     وجهةُ انحساره **يمينٌ ثابتة**: تخطيطُ الموقع ‎dir=rtl‎ لا ينقلب مع اللغة (تبدّل
     النصوصَ وحدَها)، فالبدءُ يمينٌ في الحالين ولا حاجةَ إلى نظيرٍ للإنجليزيّة.
     والكسرُ يُكتب على العنصر، والانتقالُ ثانيةٌ خطّيّة — فينحسر **جريانًا لا قفزًا**.
     ولا يرتدّ عند تصفير السؤال: ‎xtPaint‎ تبني العنصرَ من جديدٍ بكسره الجديد، والمولودُ
     لتوّه لا ينتقل إذ لا قيمةَ سابقةً يُنتقل منها — فيُولد ممتلئًا بلا رجعة. */
  const xtClkFrac = () => (xtClk && xtClk.tot)
    ? Math.max(0, Math.min(1, xtClk.left / xtClk.tot)) : 1;
