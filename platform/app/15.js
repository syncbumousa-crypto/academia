  function xtUnstick(a) {
    const n = a.length;
    const fits = (p, x) => (p <= 0 || a[p - 1].cid !== x.cid) && (p >= n - 1 || a[p + 1].cid !== x.cid);
    for (let i = 1; i < n; i++) {
      if (a[i].cid !== a[i - 1].cid) continue;
      for (let d = 2; d < n; d++) {
        let done = false;
        for (let t = 0; t < 2; t++) {
          const j = t ? i - d : i + d;
          if (j < 0 || j >= n || a[j].cid === a[i].cid) continue;
          const u = a[i], v = a[j];
          a[i] = v; a[j] = u;
          if (fits(i, v) && fits(j, u)) { done = true; break; }
          a[i] = u; a[j] = v;
        }
        if (done) break;
      }
    }
    return a;
  }
