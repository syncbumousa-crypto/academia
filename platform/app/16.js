  /* ---------- شريط تمرير مخصّص (#xscroll): عنصر DOM نبنيه ونتحكّم في جهته حسب اللغة —
     مفصول عن المتصفح، فيتغيّر مكانه فعلًا (يسار عربي/يمين إنجليزي) عبر html[data-lang] ---------- */
  (function customScrollbar() {
    const scroller = document.body;
    const bar = document.createElement('div'); bar.id = 'xscroll';
    bar.innerHTML = '<button type="button" id="xup" aria-label="أعلى">▲</button>' +
      '<div id="xtrack"><div id="xthumb"></div></div>' +
      '<button type="button" id="xdown" aria-label="أسفل">▼</button>';
    document.body.appendChild(bar);
    const track = bar.querySelector('#xtrack'), thumb = bar.querySelector('#xthumb');
    let dragging = false, startY = 0, startScroll = 0;
    const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
    function update() {
      const ch = scroller.clientHeight, sh = scroller.scrollHeight, st = scroller.scrollTop;
      if (sh <= ch + 2) { bar.style.display = 'none'; return; }
      bar.style.display = '';
      const trackH = track.clientHeight;
      const thumbH = Math.max(30, Math.round(trackH * ch / sh));
      const top = (sh - ch) ? Math.round((trackH - thumbH) * st / (sh - ch)) : 0;
      thumb.style.height = thumbH + 'px';
      thumb.style.transform = 'translateY(' + top + 'px)';
    }
    scroller.addEventListener('scroll', update, { passive: true });
    window.addEventListener('resize', update);
    /* سحب الإبهام */
    thumb.addEventListener('mousedown', e => {
      dragging = true; startY = e.clientY; startScroll = scroller.scrollTop;
      document.documentElement.style.userSelect = 'none'; e.preventDefault(); e.stopPropagation();
    });
    window.addEventListener('mousemove', e => {
      if (!dragging) return;
      const scrollable = scroller.scrollHeight - scroller.clientHeight;
      const trackScroll = (track.clientHeight - thumb.offsetHeight) || 1;
      scroller.scrollTop = startScroll + (e.clientY - startY) * scrollable / trackScroll;
    });
    window.addEventListener('mouseup', () => { if (dragging) { dragging = false; document.documentElement.style.userSelect = ''; } });
    /* نقر المسار = قفزة لموضعه */
    track.addEventListener('mousedown', e => {
      if (e.target === thumb) return;
      const trackScroll = (track.clientHeight - thumb.offsetHeight) || 1;
      const y = e.clientY - track.getBoundingClientRect().top - thumb.offsetHeight / 2;
      const scrollable = scroller.scrollHeight - scroller.clientHeight;
      scroller.scrollTop = clamp(y / trackScroll * scrollable, 0, scrollable);
    });
    /* السهمان: نقرة = خطوة، والاستمرار بالضغط = تمرير متواصل */
    function arrowHold(btn, dir) {
      let to, iv;
      btn.addEventListener('mousedown', e => {
        e.preventDefault(); e.stopPropagation();
        scroller.scrollTop += dir * 55;
        to = setTimeout(() => { iv = setInterval(() => { scroller.scrollTop += dir * 15; }, 16); }, 280);
      });
      const stop = () => { clearTimeout(to); clearInterval(iv); };
      btn.addEventListener('mouseup', stop);
      btn.addEventListener('mouseleave', stop);
      window.addEventListener('mouseup', stop);
    }
    arrowHold(bar.querySelector('#xup'), -1);
    arrowHold(bar.querySelector('#xdown'), 1);
    /* تحديث عند تغيّر ارتفاع المحتوى (رسم لوحة/مساهمات...) */
    if (window.ResizeObserver) {
      const ro = new ResizeObserver(update);
      document.querySelectorAll('.panel').forEach(p => ro.observe(p));
    }
    update(); setTimeout(update, 200);
  })();
