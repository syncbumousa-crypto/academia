  function xtOptPct(u) {
    const n = xtNodeOf(u.cid);
    const o = (n && n.a && n.a.o) || null;
    if (!o) return null;
    const keys = Object.keys(o);
    let tot = 0;
    keys.forEach(k => { tot += (+o[k] || 0); });
    if (!tot) return null;
    const out = {}, rem = [];
    let sum = 0;
    keys.forEach(k => {
      const exact = (+o[k] || 0) * 100 / tot;
      const fl = Math.floor(exact);
      out[k] = fl; sum += fl;
      rem.push([k, exact - fl]);
    });
    rem.sort((a, b) => b[1] - a[1]);
    for (let i = 0; sum < 100 && i < rem.length; i++, sum++) out[rem[i][0]]++;
    return out;
  }
