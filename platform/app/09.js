  /* ============================================================
     أفسِح للقادمة — لِمَن تعود من لسانها لا لِمَن تُولد
     ============================================================
     ‎cdCascade‎ تُنادى عند الميلاد قبل أن تُدفع المولودةُ في ‎cdWins‎، فتُزاح القائماتُ
     وتنزل هي في المتن. وأمّا **العائدةُ من لسانها** فهي في القائمة من قبلُ وقد رُفع
     عنها وسمُ الطيّ — فكانت تُزاح مع القائمات جميعًا، فيتحرّك الكلُّ خطوةً واحدةً
     ويبقى بينها ما كان: تنزل فوق أمّها بالضبط، فيُظنّ أن لا نافذةَ إلّا هي.
     فتُستثنى القادمةُ من الإزاحة، وتُزاح القائماتُ وحدَهنّ — وهي المسألةُ بعينها.

     ===== ولا يُبدَّل موضعٌ اختاره صاحبُه =====
     إن كان للعائدة ‎dx/dy‎ فقد جُرّت بيدٍ إلى حيث هي، فتعود إلى موضعها ولا تُزاح
     القائماتُ: لا تصادمَ أصلًا، والإزاحةُ علاجُ تصادمٍ لا عادةٌ تُجرى.

     ===== ولا تُزاح إن لم يكن ثَمّ جار =====
     نافذةٌ وحدَها في المسرح تنزل حيث كانت، فلا معنى لخطوةٍ تُزيحها عن وسط الشاشة. */
