  function cdMinSlots() {
    const order = cdWins.filter(w => w.picked).sort((a, b) => cdBorn(a) - cdBorn(b));
    const out = [], seen = new Set();
    order.forEach(w => {
      const g = cdGid(w);
      if (!g) { out.push({ g: '', wins: [w] }); return; }
      if (seen.has(g)) return;
      seen.add(g);
      const mem = order.filter(x => cdGid(x) === g)
        .sort((a, b) => (a.ro ? 1 : 0) - (b.ro ? 1 : 0) || (a.faceK || 0) - (b.faceK || 0));
      out.push({ g: mem.length > 1 ? g : '', wins: mem });
    });
    return out;
  }
