  /* نافذةٌ جديدة فوق التي قبلها: نوعُها مختارٌ من الدُّرج، ووجهتُها وجهةُ أختها —
     فمن يضيف بطاقةً وهو في ملفٍّ يريدها فيه. وتُزاح قليلًا كنوافذ المكاتب،
     فيُرى أنّ تحتها أخرى ولا تحجبها تمامًا */
  /* و‎like‎ نافذةٌ تُخلَف الجديدةُ مكانَها: ترث موضعَها ومقاسَها **بالضبط** فلا تُزاح الكومةُ
     ولا تقفز البطاقةُ إلى الوسط. تلزم حين يجتمع «تُغلق البطاقة» و«تُفتح جديدة»: العينُ
     تقرأ ذلك استبدالَ ورقةٍ في مكانها لا نافذةً ثانيةً في مكانٍ ثالث.
     وإن كانت السابقةُ ملصقةً وُرِث الإلصاقُ أيضًا، وأُخذ موضعُها المفكوك من وديعتها (‎pre‎)
     لا من إزاحتها — فالملصقةُ إزاحتُها صفرٌ، ولو نُسخت لَعادت الجديدةُ إلى الوسط عند فكّها */
  function cdSpawn(k, like, keep) {
    const src = cardDlg;
    const el = cdWinEl();
    /* ===== والمولودةُ ترث وجهةَ أمّها =====
       منتقي النوع يُولّد **نافذةً جديدة** لا يبدّل المركَّزة. فلو لم تُورَّث الوجهةُ
       لَاختار المستخدمُ نوعًا في «رحلتي» فنزلت بطاقتُه في رزمة مساهمةٍ في المكتبة —
       والدُّرجُ نزل من رحلته.
       والمدخلةُ تُورَّث من الأمّ لا تُقرأ من ‎nookEntry‎: تلك الشاشةُ خلف النافذة،
       وقد تكون تبدّلت */
    const w = cdWinState(src ? src.pid : null, null, el, k, src && src.road);
    if (src && src.road) w.roadE = src.roadE;
    /* والدُّرجُ يُورَّث: من أخذ نوعًا وهو مبسوطٌ يريده مبسوطًا بعدَه، فقد يأخذ ثانيًا.
       فإن لم تكن نافذةٌ تُورِّث (كلُّهنّ مطويّات) فحالُه في الصفحة هو الخبر */
    /* ===== والمولودةُ تُطوى دُرجَها كذلك =====
       كانت ترث حالَ أمّها (‎src.tray‎)، وأمُّها إنّما كان دُرجُها مبسوطًا **لأنّك تختار
       منه** — فإذا اخترتَ فقد قُضي الأمر. ووراثةُ البسط تُبقي الحالَ «مبسوط» في نافذةٍ
       جديدةٍ لا حاجةَ لها به، فينبسط الدُّرجُ كلّما رُكّزت أو أُعيد رسمُها.
       وهي علّةُ أختِها في مسار الاختيار الأوّل سواءً بسواء */
    /* ولا يُمَسّ الدُّرج عند الميلاد: هو مبسوطٌ لأنّك تختار منه، ويبقى لِمَن
       يريد نوعًا ثانيًا. وحالُه واحدةٌ للشاشة فلا تُورَّث ولا تعلق في نافذة */
    if (like) {
      const p = like.snap ? (like.pre || { dx: 0, dy: 0 }) : { dx: like.dx || 0, dy: like.dy || 0 };
      w.dx = p.dx || 0; w.dy = p.dy || 0;
      w.w = like.w; w.h = like.h;
      /* والسابقةُ باقيةٌ (‎keep‎) فلا تُطمس تحتها: الجديدةُ أمامها منزاحةً إلى **أسفلَ ويسار**
         بالخطوة نفسِها — فيُرى طرفُ التي تحتها ويُعرف أنّهما اثنتان لا واحدة */
      if (keep) {
        const mx = innerWidth / 2 - 90, my = innerHeight / 2 - 70;
        w.dx = Math.max(w.dx - CD_STEP, -mx);
        w.dy = Math.min(w.dy + CD_STEP, my);
      }
    } else cdCascade();   /* ما كان في الوسط يُزاح، والجديدةُ تنزل مكانه */
    cdWins.push(w);
    el.classList.add('is-arriving');
    cdFocusWin(w);
    cdFill('', '');
    cdRange = null;
    renderCardDlg();
    /* والمولودةُ من الدُّرج مثلُها: قد تنزل على مسرحٍ فيه وعاءُ خياراتٍ لبطاقةٍ مضت */
    cdQBody(true);
    cdApplyPos(); cdApplySize();
    /* والإلصاقُ يُورَّث في البديلة وحدها: ملصقتان في الملء تُخفي إحداهما الأخرى تمامًا،
       فالباقيةُ مع الجديدة تأخذ مقاسَ سابقتها المفكوك لا إلصاقَها */
    if (like && like.snap && !keep) cdSnapTo(like.snap, true);
    void el.offsetWidth;
    el.classList.remove('is-arriving');
    setTimeout(() => { const fr = $('#cd-front'); if (fr) fr.focus(); }, 30);
  }
  /* ‎opt‎: ‎{ ro, pub }‎ — ‎ro‎ تُفتح مقفلةً، و‎pub‎ هويّةُ المساهمة المنشورة إن كانت منها */
  function openCardDlg(pid, node, road, opt) {
    const ro = !!(opt && opt.ro);
    /* والصدَفةُ تُكشف أوّلًا لا آخرًا: ما بعدها يقيس الصفحةَ (الشريطُ والمسارُ والقائمةُ
       والظلّ)، ولا مقاسَ في شجرةٍ ‎display:none‎ — كلُّه صفر. ولا يُرى منه شيءٌ قبل انتهاء
       الشوط، فالكشفُ المبكّر لا وميضَ فيه */
    cdOutStop();   /* فتحةٌ تسبق تمامَ الانصراف تُلغيه — ولا تنصرف الصدَفةُ من تحتها */
    document.getElementById('card-modal').hidden = false;
    /* ============================================================
       والانفراجُ يحتاج حالًا مطويّةً **مقيسة**
       ============================================================
       الانتقالُ لا يجري إلّا من قيمةٍ **محسوبةٍ سابقة**. والتنّورةُ تفقدها بثلاثة أبواب:
         · ‎#card-modal.is-noadd .cd-dw__tray { display: none }‎ — والمعدومُ لا يُقاس.
         · والصدَفةُ نفسُها ‎hidden‎ قبل السطر أعلاه — فالشجرةُ كلُّها بلا مقاس.
         · و**‎cdShellHide‎ لا تنزع ‎is-open‎ عن الدُّرج** حين تُخفي الصدَفة، فيعود في
           الفتحة التالية مبسوطًا أصلًا: لا انتقالَ لأنّه لم يتحرّك.
       و‎cdTrayOn()‎ تردّ ‎true‎ فورًا لبطاقةٍ في البوّابة (‎!picked‎)، فيُضاف ‎is-open‎ في
       **أوّل** رسمة — فلا فرصةَ لإطارٍ يُثبّت المطويَّ بينهما.
       وفي المكتبة تخفّ العلّةُ لأنّ الصدَفةَ تبقى مكشوفةً بين بطاقةٍ وأخرى (‎cdShutCard‎
       تردّك إلى الباب ولا تُخرجك من الغرفة)، فالتنّورةُ قائمةٌ مقيسةٌ منذ إطارٍ سابق.
       فيُصنع الحالُ الابتدائيُّ ههنا صراحةً: تُرفع الحجبة، ويُطوى الدُّرج، ثمّ **يُقاس**
       — والقياسُ المُجبَر (‎offsetHeight‎) أوثقُ من انتظار إطارِ رسمٍ وأسرع.
       وما يُنزع ههنا يردّه ‎cdDrawerSync‎ في الرسمة نفسِها إن كان واجبًا، فلا يُرى فرق */
    {
      const m0 = document.getElementById('card-modal');
      const dw0 = document.getElementById('cd-drawer');
      const tray0 = dw0 && dw0.querySelector('.cd-dw__tray');
      if (tray0) {
        /* الحجبةُ تُرفع أوّلًا وإلّا لم يُقَس المحجوب */
        m0.classList.remove('is-noadd');
        /* ونبدأ من المطويّ **يقينًا**: ‎cdShellHide‎ تُخفي الصدَفةَ ولا تنزع ‎is-open‎ عن
           الدُّرج، فيعود في الفتحة التالية مبسوطًا أصلًا — فلا انتقالَ لأنّه لم يتحرّك */
        dw0.classList.remove('is-open');
        /* ثمّ قياسٌ مُجبَر: به وحدَه يصير ‎max-height: 0‎ قيمةً محسوبةً يبدأ منها الانتقال */
        void tray0.offsetHeight;
      }
    }
    /* بطاقةٌ مفتوحةٌ في نافذةٍ لا تُفتح في ثانية: تُركَّز التي فيها — وإلّا صار للعقدة
       الواحدة محرّران يكتب كلٌّ منهما فوق الآخر */
    if (node) {
      /* ===== والمقصودُ **محرّرٌ** لهذه العقدة لا كلُّ نافذةٍ تحمل معرّفَها =====
         حجّةُ هذه القاعدة أنّ محرّرَين على عقدةٍ واحدة يكتب كلٌّ منهما فوق الآخر. ولذلك
         استُثنيت المقفلةُ (‎ro‎): معاينةُ وجهٍ لا تكتب، فلو حُسبت لَردّت من أراد التحريرَ
         إلى ما لا يُحرَّر.
         ونافذةُ الاختبار مثلُها بل أولى: هي **تستعير معرّفَ البطاقة الجارية** لتُعرف
         نسختُها وتعليقاتُها ومَن عندها (‎renderXtDlg‎ تكتب ‎cardDlg.id‎) — ولا تكتب حرفًا.
         فكانت تُلتقط ههنا، فمن امتُحن ببطاقةٍ ثمّ طواها وذهب يحرّرها **فُتح له الاختبارُ
         مكانَ المحرّر**. فالشرطُ جنسُ النافذة لا أثرٌ من آثاره */
      /* والمقفلةُ لا تُخلط بالمحرَّرة: قد تكون البطاقةُ مفتوحةً للتحرير في رزمتك
         ومقفلةً من مساهمةٍ منشورة — وهما نافذتان لا واحدة.
         و‎faceK == null‎ يستثني نوافذَ الوجوه: تلك لها مصالحتُها في ‎czFaceOpen‎ */
      const had = cdWins.find(w => w.what === 'card' && w.faceK == null
        && !!w.ro === ro && w.id === node.id);
      if (had) { cdFocusWin(had); return; }
    }
    /* والنافذةُ الثانية تُضاف ولا تُزيل الأولى — إلّا أن يكون المسرحُ خاليًا فتُبتدأ به.
       ===== ومسرحُ المقفلة مستنسَخٌ دائمًا =====
       هي تكتب في مسرحها: تزرع أقفالًا وترفع القلمَ عن حقوله. والأصليُّ (‎cdBase‎) مسكنُ
       أوّل نافذةٍ في كلّ فتحةٍ قادمة، فما يُكتب فيه يرثه من بعدها — وهي العلّةُ المكتوبةُ
       في ‎czFaceOpen‎ بحروفها */
    const el = ro ? shWinEl() : cdWinEl();
    const w = cdWinState(pid, node, el, null, road);
    if (ro) { w.ro = true; if (opt && opt.pub) w.pub = opt.pub; }
    if (cdWins.length) cdCascade();
    cdWins.push(w);
    /* وأوجهُها تنزل ألسنةً معها — **في المحرَّرة وحدَها**: المقفلةُ فُتحت لتُقرأ بطاقةٌ
       بعينها، وإنزالُ أوجهها ألسنةً معها يفتح ثلاثَ نوافذَ لضغطةٍ واحدة. ومن أراد وجهًا
       فتحه من مثلّثه */
    if (node && !ro) cdKinOpen(node, pid);
    cdFocusWin(w);
    cdFill(node ? node.f : '', node ? node.b : '');
    cdRange = null;
    renderCardDlg();
    /* ===== ووعاءُ الخيارات يُبنى من جديدٍ عند مولد كلّ نافذة =====
       ‏‎cdQBody‎ لا تبني الصناديقَ إلّا عند مولد الوعاء أو بطلبٍ صريح (‎force‎)، وحجّتُها
       أنّ ‎renderCardDlg‎ تُستدعى من عشرة أبواب فلا يُقفز المؤشّرُ من تحت اليد.
       و‎cdWinEl‎ **تُعيد استعمال المسرح الأصل** (‎cdBase‎) متى خلا من نافذةٍ حيّة — فالوعاءُ
       يبقى في الصفحة بصناديق البطاقة التي مضت. فإذا فُتحت بطاقةٌ أخرى عليه لم يُعَد بناؤه
       (‎fresh‎ كاذبةٌ ولا ‎force‎)، فتُعرض خياراتُ السابقة في الجديدة — ثمّ **يقرؤها
       ‎cdCommit‎ من الصفحة فيكتبها في عقدة الجديدة**، فتنتقل الخياراتُ حقًّا لا عرضًا.
       وهو عطبٌ لا يخصّ الرَّكن: يقع بين بطاقتين في المكتبة سواءً بسواء.
       والمولدُ «بطاقةٌ أخرى» بحدّه، فيُطلب البناءُ صراحةً كما يُطلب في ‎cdShow‎ */
    cdQBody(true);
    cdApplyPos();
    /* بطاقةٌ جديدة: الدُّرج ينسحب وحده — لكن **بعد** أن تُحسب حالتُه المطويّة على شاشةٍ ظاهرة،
       وإلّا وُجد مبسوطًا من أوّل إطارٍ فظهر ظهورًا ولم يُرَ انسحابُه.
       والإجبار على إعادة التخطيط (‎offsetWidth‎) هو ما يُثبّت تلك الحالة المطويّة —
       وهو أوثق من انتظار إطارِ رسمٍ قد يتأخّر */
    if (!node) {
      void $('#cd-drawer').offsetWidth;
      cdTray = true;
      renderCardDlg();
    }
    if (cardDlg.picked) setTimeout(() => $('#cd-front').focus(), 30);
  }
  /* ===== «✕» تُنهي البطاقة لا الجلسة =====
     الدُّرج بابُ الإضافة، والبطاقةُ ما ينزل منه. فإغلاقُ البطاقة يردّك إلى الباب لا يُخرجك
     من الغرفة — تُغلق ما بين يديك وتأخذ نوعًا آخر بلا أن تعيد فتح كلّ شيء.
     ويبقى الدُّرج على حاله انسحابًا أو انكماشًا: حالتُه لك لا تُبدَّل عنك.
     والخروجُ الكامل بضغطةٍ على العتمة خارج الأسطح (وهي المخرج الوحيد — لا مستمعَ لـEsc هنا) */
  function cdShutCard() {
    if (!cardDlg) { closeCardDlg(); return; }
    /* ============================================================
       ✕ تطوي إن بقي من عُصبتها أخٌ **قائم**
       ============================================================
       العُصبةُ أمٌّ وأوجهُها، وألسنتُها في الحافّة صفٌّ ملتحمٌ يُقرأ جسمًا واحدًا. فلو
       نُزع منها لسانٌ وإخوتُه على المسرح لَنقص الجسمُ وهو يُنظر إليه: نافذةٌ ذهبت
       ولسانُها ذهب معها، فيُقرأ أنّ الوجهَ نفسَه ذهب من البطاقة لا أنّك نحّيتَه.
       فما دام في العُصبة أخٌ قائمٌ فالعُصبةُ **حاضرةٌ**، والخارجُ منها إنّما يُنحّى
       إلى حافّتها لا يُنزع منها. وهذا نصُّ طلب صاحب الموقع: «وكأنّي سويتُ لها ‎-‎:
       تروح النافذةُ، وتبقى موجودةً فوقُ كـ‎-‎».
       ولا تُحبس البطاقةُ بذلك: آخرُ قائمةٍ في العُصبة ✕ تُنهي العُصبةَ بأسرها
       (‎cdCloseWin‎ تكنس المطويّاتِ معها إذ لم يبقَ من يعمل فيه) — فضغطتان تُذهبانها.
       ===== وهو نقضُ «✕ تُغلق. نقطة» في موضعه وحدَه =====
       تلك قاعدةٌ في **النافذة المفردة**: زرُّ إغلاقٍ لا يُغلق عَطَل. وهذه في **العُصبة**:
       ما هو نصفُ جسمٍ قائمٍ لا يُنزع وحدَه. ولا تعارضَ — إذ لا عُصبةَ للمفردة أصلًا
       (‎cdGid‎ تردّ خاويةً لما لا نسبَ له: الوجهين والمتعدّد وورقة الملخّص).
       ===== والحكمُ ههنا لا في ‎cdCloseWin‎ =====
       فتلك يناديها الكنسُ أيضًا: وجهٌ سقط من متن أمّه، وبطاقةٌ حُذفت من الشجرة —
       وتلك أعيانٌ ذهبت، فلسانٌ يُخلَّف عنها يشير إلى ما ليس بموجود.
       فالطيُّ حكمُ **الضغطة** لا حكمُ الانصراف */
    {
      const g = cdGid(cardDlg);
      if (g && cdWins.some(x => x !== cardDlg && !x.min && cdGid(x) === g)) {
        cdMinWin(cardDlg);   /* الطريقُ نفسُه الذي يسلكه زرُّ ‎-‎، بحركته وإيداعه */
        return;
      }
    }
    clearTimeout(cdT);
    cdCommit();
    /* ===== ✕ تُغلق. نقطة =====
       ولا شأنَ للترس بها البتّة: مفتاحاه يقولان ما يقع **عند الحفظ** (ضغطةُ الحلقة) كما
       يقول لفظُهما، لا ما يقع عند الإغلاق. وقد رُبطا بها فصار زرُّ إغلاقٍ لا يُغلق —
       وزرٌّ لا يفعل ما يقوله اسمُه عَطَلٌ مهما كان الإعدادُ وراءه صحيحًا في نفسه */
    cdSweepBlank();
    /* ============================================================
       المشهدُ أوّلًا، والدفترُ بعده
       ============================================================
       كان الترتيبُ: احفظ الحالَ · نظّف · أعِد بناءَ الشجرة · ثمّ أغلق. وثلاثتُها أعمالٌ
       طويلةٌ **متزامنة**: ‎save‎ تكتب الحالَ كلَّها في الدرج، و‎edRender‎ تعيد بناء الشجرة
       من جذرها. فتقع كلُّها بين ضغطتك وأوّل إطارٍ من الحركة — فتبدأ متأخّرةً متقطّعة،
       وهو الثِّقلُ الذي يُحَسّ.
       فيُقدَّم ما يُرى ويُؤخَّر ما لا يُرى: ‎cdCloseWin‎ تضع أصنافَ الحركة الآن، ثمّ
       يُترك الدفترُ لِما بعد أوّل إطار.
       و‎requestAnimationFrame‎ ثمّ ‎setTimeout‎: الأوّلُ يبلغ حافّةَ الإطار، والثاني
       يُخرج العملَ من شوطه — فيقع الرسمُ ثمّ يقع الثقيل.
       والتأخيرُ لا يُضيّع شيئًا: ‎cdCommit‎ في صدر هذه الدالّة حفظت ما كُتب أصلًا،
       وهذه حفظةُ ما نظّفه ‎cdSweepBlank‎ — والشجرةُ خلفها تلحق مؤجَّلةً مجموعة */
    const w = cardDlg;
    cdCloseWin(w);
    requestAnimationFrame(() => setTimeout(() => {
      save(); cleanupEmptyMine(); cdEdDraw();
    }, 0));
  }
