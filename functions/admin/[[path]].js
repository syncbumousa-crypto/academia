/* ============================================================
   ‎/admin/*‎ — البابُ القديم، يُردّ ٤٠٤ بيقين
   ============================================================
   نُقلت اللوحةُ إلى مسارٍ لا يُخمَّن. وحذفُ الملفّات وحدَه لا يكفي: خبءُ حافّة
   كلاودفلير احتفظ بالنسخة القديمة وظلّ يقدّمها ‎٢٠٠‎ لعشر دقائق، ولا يستجيب
   لـ‎no-cache‎ من طالبها.

   والدالّةُ تسبق الملفّات الساكنة وتُقدَّم من الخادم لا من الخبء — فيموت البابُ
   في اللحظة نفسِها. و‎no-store‎ تمنع أن يُخبَّأ هذا الردُّ بدوره.

   وتبقى ما بقيت اللوحةُ منقولة: سطرٌ يُحذف يومَ يُنسى أنّ ثمّة بابًا كان. */
export async function onRequest() {
  return new Response(JSON.stringify({ error: 'not-found' }), {
    status: 404,
    headers: {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': 'no-store, must-revalidate',
    },
  });
}
